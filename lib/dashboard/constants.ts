/** Gap as a fraction of the square cell size. */
export const GAP_RATIO = 0.08;

/** Minimum gap between cells (px). */
export const GAP_MIN_PX = 4;

/** Maximum gap between cells (px). */
export const GAP_MAX_PX = 20;
